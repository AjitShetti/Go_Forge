// Writes supabase/migrations/20260915000600_scenarios_p7.sql (every scenario, upserted) from src/lib/grader/scenarios.ts,
// so the scenarios table carries exactly what the grader uses.
//   node scripts/gen-scenarios-sql.mjs
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const { SCENARIOS } = await import("../src/lib/grader/scenarios.ts");
const q = (v) => `'${String(v).replaceAll("'", "''")}'`;
const rows = SCENARIOS.map(
  (s) =>
    `  (${q(s.slug)}, ${q(s.title)}, ${q(JSON.stringify({ summary: s.summary, functional: s.functional, scale: s.scale, params: s.params }))}::jsonb, ${q(JSON.stringify(s.constraints))}::jsonb, ${q(JSON.stringify(s.rules))}::jsonb)`,
);
const sql = `-- P7: all grading scenarios (P6 seeded the first in 20260915000500). GENERATED by scripts/gen-scenarios-sql.mjs from
-- src/lib/grader/scenarios.ts; edit that file and regenerate. The grader runs
-- from the TypeScript; these rows let designs.scenario_id point at a scenario.
insert into public.scenarios (slug, title, requirements, constraints, rules) values
${rows.join(",\n")}
on conflict (slug) do update set title = excluded.title, requirements = excluded.requirements, constraints = excluded.constraints, rules = excluded.rules;
`;
writeFileSync(resolve(root, "supabase", "migrations", "20260915000600_scenarios_p7.sql"), sql);
console.log(`wrote ${SCENARIOS.length} scenario(s)`);
